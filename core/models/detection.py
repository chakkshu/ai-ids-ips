"""Detection Model.

Stores real-time classification inferences, anomaly scores, confidence values,
and top contributing feature attributions generated by the detection engine.
"""

from __future__ import annotations

from datetime import UTC, datetime
from typing import TYPE_CHECKING

from sqlalchemy import (
    BigInteger,
    Boolean,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from core.db import Base

if TYPE_CHECKING:
    from core.models.alert import Alert
    from core.models.network import NetworkFlow


class Detection(Base):
    """Machine learning inference result corresponding to an analyzed network flow."""

    __tablename__ = "detections"

    id: Mapped[int] = mapped_column(
        BigInteger().with_variant(Integer, "sqlite"),
        primary_key=True,
        autoincrement=True,
    )
    flow_id: Mapped[int] = mapped_column(
        BigInteger().with_variant(Integer, "sqlite"),
        ForeignKey("network_flows.id", ondelete="CASCADE"),
        nullable=False,
        unique=True,
        index=True,
    )
    
    timestamp: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(UTC),
        nullable=False,
        index=True,
    )

    # Inferred Classifications
    predicted_label: Mapped[str] = mapped_column(String(64), nullable=False, index=True)
    is_malicious: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False, index=True)
    confidence_score: Mapped[float] = mapped_column(Float, nullable=False)
    
    # Anomaly Layer (Isolation Forest)
    is_anomaly: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    anomaly_score: Mapped[float] = mapped_column(Float, default=0.0, nullable=False)

    # Explainability & Attribution (Top contributing features stored as JSON)
    top_features_json: Mapped[str | None] = mapped_column(Text, nullable=True)
    
    # Telemetry & Governance
    model_version: Mapped[str] = mapped_column(String(32), nullable=False, index=True)
    inference_latency_ms: Mapped[float] = mapped_column(Float, default=0.0, nullable=False)

    # Relationships
    flow: Mapped[NetworkFlow] = relationship("NetworkFlow", back_populates="detection")  # type: ignore
    alerts: Mapped[list[Alert]] = relationship("Alert", back_populates="detection", cascade="all, delete-orphan")  # type: ignore

    __table_args__ = (
        Index("ix_detections_malicious_time", "is_malicious", "timestamp"),
        Index("ix_detections_label_conf", "predicted_label", "confidence_score"),
    )

    def __repr__(self) -> str:
        return f"<Detection id={self.id} label='{self.predicted_label}' conf={self.confidence_score:.2f} mal={self.is_malicious}>"
